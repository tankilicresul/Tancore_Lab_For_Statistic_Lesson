ALTER TABLE public.course_notes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.app_issues ENABLE ROW LEVEL SECURITY;

-- =========================================================================
-- 3. RLS POLİTİKALARI
-- =========================================================================

-- PROFILES:
DROP POLICY IF EXISTS "Profiles are readable by authenticated users" ON public.profiles;
DROP POLICY IF EXISTS "Users can insert their own profile" ON public.profiles;
DROP POLICY IF EXISTS "Users can update own profile" ON public.profiles;
DROP POLICY IF EXISTS "Users can delete own profile" ON public.profiles;

CREATE POLICY "Profiles are readable by authenticated users"
ON public.profiles FOR SELECT
TO authenticated, anon
USING (true);

CREATE POLICY "Users can insert their own profile"
ON public.profiles FOR INSERT
TO authenticated
WITH CHECK (auth.uid() = id);

CREATE POLICY "Users can update own profile"
ON public.profiles FOR UPDATE
TO authenticated
USING (auth.uid() = id)
WITH CHECK (auth.uid() = id);

CREATE POLICY "Users can delete own profile"
ON public.profiles FOR DELETE
TO authenticated
USING (auth.uid() = id);

-- TANCO CHATS:
DROP POLICY IF EXISTS "Users can read their own chats" ON public.tanco_chats;
DROP POLICY IF EXISTS "Users can insert their own chats" ON public.tanco_chats;
DROP POLICY IF EXISTS "Users can delete their own chats" ON public.tanco_chats;

CREATE POLICY "Users can read their own chats"
ON public.tanco_chats FOR SELECT
TO authenticated
USING (auth.uid()::text = user_id OR auth.jwt() ->> 'email' = user_email);

CREATE POLICY "Users can insert their own chats"
ON public.tanco_chats FOR INSERT
TO authenticated
WITH CHECK (auth.uid()::text = user_id OR auth.jwt() ->> 'email' = user_email);

CREATE POLICY "Users can delete their own chats"
ON public.tanco_chats FOR DELETE
TO authenticated
USING (auth.uid()::text = user_id OR auth.jwt() ->> 'email' = user_email);

-- USER PROGRESS:
DROP POLICY IF EXISTS "Users can read own progress" ON public.user_progress;
DROP POLICY IF EXISTS "Users can upsert own progress" ON public.user_progress;

CREATE POLICY "Users can read own progress"
ON public.user_progress FOR SELECT
TO authenticated
USING (auth.uid()::text = user_id);

CREATE POLICY "Users can upsert own progress"
ON public.user_progress FOR ALL
TO authenticated
USING (auth.uid()::text = user_id)
WITH CHECK (auth.uid()::text = user_id);

-- COURSE NOTES:
DROP POLICY IF EXISTS "Anyone can view course notes" ON public.course_notes;
DROP POLICY IF EXISTS "Authenticated users can upload course notes" ON public.course_notes;

CREATE POLICY "Anyone can view course notes"
ON public.course_notes FOR SELECT
TO authenticated, anon
USING (true);

CREATE POLICY "Authenticated users can upload course notes"
ON public.course_notes FOR INSERT
TO authenticated, anon
WITH CHECK (true);

-- APP ISSUES:
DROP POLICY IF EXISTS "Anyone can report issues" ON public.app_issues;
CREATE POLICY "Anyone can report issues"
ON public.app_issues FOR INSERT
TO authenticated, anon
WITH CHECK (true);

-- =========================================================================
-- 4. GÜVENLİ LİDERLİK GÖRÜNÜMÜ (KVKK / Privacy Compliant View)
-- =========================================================================

CREATE OR REPLACE VIEW public.public_leaderboard AS
SELECT
    id,
    full_name,
    university,
    department_and_class,
    avatar_emoji,
    avatar_url,
    xp,
    streak,
    completed_lessons
FROM public.profiles
ORDER BY xp DESC;

-- =========================================================================
-- 5. SUNUCU TARAFLI GÜVENLİ PUANLAMA (RPC FUNCTION)
-- =========================================================================

CREATE OR REPLACE FUNCTION public.complete_lesson_secure(
    p_lesson_id TEXT,
    p_module_id TEXT,
    p_xp_to_award INTEGER DEFAULT 15
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_user_id UUID := auth.uid();
    v_capped_xp INTEGER;
BEGIN
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Bu işlemi gerçekleştirmek için oturum açmalısınız.';
    END IF;

    -- Güvenlik sınırı: Tek bir dersten en fazla 50 XP kazanılabilir
    v_capped_xp := LEAST(GREATEST(p_xp_to_award, 0), 50);

    UPDATE public.profiles
    SET xp = xp + v_capped_xp,
        completed_lessons = completed_lessons + 1,
        updated_at = NOW()
    WHERE id = v_user_id;

    RETURN jsonb_build_object(
        'success', true,
        'lesson_id', p_lesson_id,
        'module_id', p_module_id,
        'awarded_xp', v_capped_xp
    );
END;
$$;
