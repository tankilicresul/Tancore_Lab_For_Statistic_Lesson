-- 1. TABLOLARIN OLUŞTURULMASI (Eğer Mevcut Değilse)

CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT UNIQUE NOT NULL,
    full_name TEXT,
    university TEXT,
    department_and_class TEXT,
    avatar_emoji TEXT DEFAULT '👨‍🎓',
    avatar_url TEXT,
    xp INTEGER DEFAULT 0 CHECK (xp >= 0),
    streak INTEGER DEFAULT 1 CHECK (streak >= 1),
    completed_lessons INTEGER DEFAULT 0 CHECK (completed_lessons >= 0),
    device_id TEXT,
    device_info TEXT,
    is_verified BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.user_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL UNIQUE,
    total_xp INTEGER DEFAULT 0,
    level INTEGER DEFAULT 1,
    streak INTEGER DEFAULT 1,
    completed_lessons JSONB DEFAULT '[]'::jsonb,
    completed_case_exams JSONB DEFAULT '[]'::jsonb,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.tanco_chats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL,
    user_email TEXT,
    sender TEXT NOT NULL CHECK (sender IN ('tanco', 'student')),
    text TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.course_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code TEXT NOT NULL,
    course_title TEXT,
    file_name TEXT NOT NULL,
    file_size BIGINT DEFAULT 0,
    file_type TEXT,
    file_url TEXT,
    uploader_email TEXT,
    uploader_name TEXT,
    note_description TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.app_issues (
    id TEXT PRIMARY KEY,
    user_message TEXT NOT NULL,
    detected_issue TEXT,
    screen_context TEXT,
    user_email TEXT,
    user_name TEXT,
    severity TEXT DEFAULT 'Medium',
    status TEXT DEFAULT 'Open',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- =========================================================================
